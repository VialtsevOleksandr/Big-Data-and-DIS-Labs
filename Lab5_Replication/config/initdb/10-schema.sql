-- Схема сервісу нотаток. Виконується один раз під час initdb на вузлі, що стартує з порожнім томом.
-- У конфігурації A це лише лідер (фоловери отримують схему з pg_basebackup),
-- у конфігурації B — обидва лідери (логічна реплікація DDL не передає).

CREATE TABLE notes (
    -- Ідентифікатор генерує сама база. BY DEFAULT дозволяє логічній реплікації
    -- вставляти рядок із готовим id, отриманим з іншого вузла.
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id  integer     NOT NULL,
    title      text        NOT NULL,
    body       text        NOT NULL,
    -- Час останньої зміни: виставляється при створенні й оновлюється в кожному UPDATE застосунку.
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Список нотаток автора, найновіші першими.
CREATE INDEX notes_author_updated_idx ON notes (author_id, updated_at DESC);
