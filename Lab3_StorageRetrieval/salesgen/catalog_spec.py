"""Декларативний опис синтетичного каталогу (українською).

Тут лише *шаблони*: категорії, типи товарів, сорти/варіанти, фасування,
базові ціни та моделі кількості. Конкретні 2 000 товарів будує
`catalog.py` детерміновано з seed.

Позначення:
  ref-одиниця типу  — одиниця, в якій задана базова ціна (кг, л або шт.);
  pk(...)           — фасований товар, облікова одиниця pcs;
  wt(...)           — ваговий товар, облікова одиниця kg;
  dr(...)           — розливний товар, облікова одиниця l.

Усі бренди та «лінійки» вигадані; збіг із реальними назвами випадковий.
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Pack:
    label: str
    unit: str            # 'pcs' | 'kg' | 'l'
    size: float          # скільки ref-одиниць в одній обліковій одиниці (для pcs); 1.0 для kg/l
    factor: float        # множник ціни відносно базової ціни за ref-одиницю
    weight: float        # відносна популярність такого фасування в межах типу
    # модель кількості для pcs: q = Geometric(geom_p), обрізано до max_q
    geom_p: float = 0.0
    max_q: int = 0
    # модель кількості для kg/l: LogNormal(ln(median), sigma), обрізано до [lo, hi]
    median: float = 0.0
    sigma: float = 0.0
    lo: float = 0.0
    hi: float = 0.0


def pk(label: str, size: float = 1.0, factor: float = 1.0, p: float = 0.75,
       maxq: int = 6, w: float = 1.0) -> Pack:
    return Pack(label, "pcs", size, factor, w, geom_p=p, max_q=maxq)


def wt(median: float, sigma: float = 0.45, lo: float = 0.05, hi: float = 5.0,
       factor: float = 1.0, w: float = 1.0, label: str = "на вагу") -> Pack:
    return Pack(label, "kg", 1.0, factor, w, median=median, sigma=sigma, lo=lo, hi=hi)


def dr(median: float, sigma: float = 0.4, lo: float = 0.3, hi: float = 6.0,
       factor: float = 0.85, w: float = 0.6, label: str = "розливне") -> Pack:
    return Pack(label, "l", 1.0, factor, w, median=median, sigma=sigma, lo=lo, hi=hi)


